"""B-1473 (CLAUDE.md thumb rule 2026-11-05): every registered strategy is re-backtested at least every 6 months.

Writes docs/RETEST_SCHEDULE.md: one row per (family, timeframe) with the number of tags, the OLDEST result date among
them and the date the family's re-test is due (oldest + 183 days). Result date, first match wins:
  1. an ISO date (YYYY-MM-DD) or "14 Oct 2026" style date in run_ref / evidence / notes / source;
  2. a GitHub Actions run id ("run 38517583883"), converted with a linear fit of two known anchors;
  3. otherwise the repo's research start (2026-09-01), the conservative earliest possible date.
Run: python scripts/retest_due.py (regenerate) | --check [--today YYYY-MM-DD] (list overdue, exit 1 if any). A re-run is registered as a NEW tag/run ref; old rows stay.
"""
import datetime as dt
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, "docs", "RETEST_SCHEDULE.md")
CYCLE_DAYS = 183
RESEARCH_START = dt.date(2026, 9, 1)
# (run id, IST date) anchors from this repo's own Actions history
_ANCHORS = ((38517583883, dt.date(2026, 10, 14)), (41956627207, dt.date(2026, 11, 5)))
_ISO = re.compile(r"\b(20\d\d)-(\d\d)-(\d\d)\b")
_DMY = re.compile(r"\b(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* (20\d\d)\b")
_RUN = re.compile(r"\brun[s]? (\d{10,12})\b")
_MON = {m: i + 1 for i, m in enumerate("Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split())}


def _run_id_date(rid: int) -> dt.date:
    (r0, d0), (r1, d1) = _ANCHORS
    per_day = (r1 - r0) / (d1 - d0).days
    return d0 + dt.timedelta(days=round((rid - r0) / per_day))


def result_date(text: str):
    """(date, how) for one registry row's combined text."""
    dates = []
    for y, m, d in _ISO.findall(text):
        try:
            dates.append(dt.date(int(y), int(m), int(d)))
        except ValueError:
            pass
    for d, mon, y in _DMY.findall(text):
        try:
            dates.append(dt.date(int(y), _MON[mon], int(d)))
        except ValueError:
            pass
    dates = [x for x in dates if x >= RESEARCH_START]
    if dates:
        return max(dates), "date"
    runs = [int(r) for r in _RUN.findall(text)]
    if runs:
        return max(_run_id_date(r) for r in runs), "run_id"
    return RESEARCH_START, "default"


def build():
    import strategy_registry as sr
    fam = {}
    for s in sr.REGISTRY:
        text = " ".join(str(x or "") for x in ((s.metrics.run_ref if s.metrics else ""), s.evidence, s.notes, s.source))
        d, how = result_date(text)
        key = (s.name.split("__")[0], s.timeframe or "?")
        f = fam.setdefault(key, {"n": 0, "oldest": d, "live": 0, "default": 0})
        f["n"] += 1
        f["oldest"] = min(f["oldest"], d)
        f["live"] += s.status.name == "LIVE"
        f["default"] += how == "default"
    rows = []
    for (family, tf), f in fam.items():
        due = f["oldest"] + dt.timedelta(days=CYCLE_DAYS)
        rows.append((due, family, tf, f))
    rows.sort(key=lambda r: (r[0], -r[3]["live"], r[1], r[2]))
    return rows


def render(rows) -> str:
    out = ["# Strategy re-test schedule (6-month cycle, B-1473)", "",
           "Generated by `scripts/retest_due.py` from `strategy_registry.REGISTRY`. One row per family and timeframe; "
           "due = oldest result in the group + 183 days. Families with live-wired tags are re-tested first. "
           "`undated` counts tags with no date or run id on record (taken as 2026-09-01, the conservative earliest).", "",
           f"Families: {len(rows)}. List what is overdue today with `python scripts/retest_due.py --check`.", "",
           "| Due | Family | TF | Tags | Live | Oldest result | Undated |", "|---|---|---|---|---|---|---|"]
    for due, family, tf, f in rows:
        out.append(f"| {due.isoformat()} | {family} | {tf} | {f['n']} | {f['live']} | {f['oldest'].isoformat()} | {f['default']} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    today = dt.date.fromisoformat(sys.argv[sys.argv.index("--today") + 1]) if "--today" in sys.argv else dt.date.today()
    rows = build()
    if "--check" in sys.argv:
        due = [r for r in rows if r[0] <= today]
        for d, family, tf, f in due:
            print(f"OVERDUE {d.isoformat()} {family} {tf} ({f['n']} tags, {f['live']} live)")
        print(len(due), "of", len(rows), "families overdue as of", today.isoformat())
        sys.exit(1 if due else 0)
    open(OUT, "w").write(render(rows))
    print(len(rows), "families written")
