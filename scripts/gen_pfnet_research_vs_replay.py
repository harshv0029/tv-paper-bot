"""Regenerate docs/PFNET_RESEARCH_VS_REPLAY.md: for every tag that has BOTH a research-stage
result and a main.py-replay result (the `_mr` twin), show the two PFnets side by side so the
gap can be re-investigated later (user 2026-10-13). Derived from strategy_registry only; both
tags keep their own stored metrics. Usage: python3 scripts/gen_pfnet_research_vs_replay.py [--check]"""
import pathlib
import sys

sys.path.insert(0, ".")
import strategy_registry as sr  # noqa: E402

OUT = pathlib.Path("docs/PFNET_RESEARCH_VS_REPLAY.md")


def _f(x, n=2):
    return "" if x is None else f"{x:.{n}f}"


def build() -> str:
    by = {s.name: s for s in sr.REGISTRY}
    rows = []
    for name, rep in by.items():
        if "_mr__" not in name:
            continue
        res = by.get(name.replace("_mr__", "__", 1))
        rm, pm = (res.metrics if res else None), rep.metrics
        if pm is None:
            continue
        d = None if rm is None or rm.pfnet is None else pm.pfnet - rm.pfnet
        flag = "no research twin" if res is None else ("replay lower" if d is not None and d < -0.3 else
                                                       "replay higher" if d is not None and d > 0.3 else "close")
        rows.append((name, res.name if res else "", rm, pm, d, flag))
    rows.sort(key=lambda r: (r[4] is None, r[4] if r[4] is not None else 0))
    L = ["# PFnet: research result vs main.py-replay result", "",
         "Generated by `scripts/gen_pfnet_research_vs_replay.py` from `strategy_registry.REGISTRY` (do not edit by hand).",
         "Research tag = original research-stage run; replay tag (`_mr`) = same rule re-run through the real `main.py` functions.",
         "Flag: |delta| > 0.3 means the two disagree and is worth re-investigating. Both tags keep their own metrics.", "",
         "| Replay tag | Research tag | Research PFnet | Research n | Replay PFnet | Replay n | Delta | Flag |",
         "|---|---|---|---|---|---|---|---|"]
    for name, rn, rm, pm, d, flag in rows:
        L.append(f"| {name} | {rn} | {_f(rm.pfnet if rm else None)} | {rm.n_trades if rm else ''} | "
                 f"{_f(pm.pfnet)} | {pm.n_trades} | {_f(d)} | {flag} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    txt = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == txt else 1)
    OUT.write_text(txt)
    print(f"wrote {OUT} ({txt.count(chr(10)) - 9} rows)")
