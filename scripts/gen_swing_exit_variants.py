"""B-1500 (2026-11-06 IST): generates swing_exit_variants_b1500.py, the per-live-tag exit-variant priority list of the
LONG daily swing engine.

User rule (CLAUDE.md WIRING RULE 2026-11-06 + B-1500): every exit variant of a live swing tag whose pooled PFnet is
> 1.00 is wired; variants are tried in RETURN-PER-DAY order (avg net return per trade % after the 0.8% cost / avg
trading days held, daily bars); the first variant whose own registry tag passes the real-money viability gate owns
the entry (main._select_swing_exit_variant).

Source: the band_cap=trail runs of swing-bandcap-replay.yml (raw JSON docs/backtest_data/swing_bandcap_run_<id>.json,
full NSE universe, REAL main.py entry/exit fns, live resting-stop model). For a live tag T the run holds one row per
exit mode m (live = fixed resting stop, live_lt*/live_tr*/live_be* = the trail overlays of scripts/swing_bandcap.py
TRAIL_RULES); the variant's registry tag is swing_bandcap.band_tag(T, m). A variant is listed only when BOTH the run
row's pooled PFnet and its registry row's PFnet are > PFNET_LIVE_FLOOR (1.00), the run row has avg_net_pct and
avg_held_bars, T is a LONG live tag the daily swing pass manages (mapped in main._STRATEGY_TAG_TO_REGISTRY_NAME, not a
1h cell, timeframe 1d/1w). A tag in several trail runs uses the LATEST run (all modes compared within one run).
Order: return per day desc, then shorter hold, then mode name (deterministic).

Run: python3 scripts/gen_swing_exit_variants.py          (writes the module)
     python3 scripts/gen_swing_exit_variants.py --check  (exit 1 when the module is stale)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

TRAIL_RUNS = ("41978699531", "42025478119", "42232093739")  # band_cap=trail runs (B-1484, B-1485, B-1495a), oldest first
OUT = os.path.join(ROOT, "swing_exit_variants_b1500.py")


def build_rows():
    import main
    import strategy_registry as sr
    import swing_bandcap as sb

    hourly = (set(main.MACDDIV_LONG_LIVE_CELLS) | set(main.ENVELOPE_LONG_LIVE_CELLS) | set(main.CUP_CHEAT_LONG_LIVE_CELLS)
              | set(main.CHAN_KALMAN_1H_CELLS) | set(main.BRK20_1H_LONG_CELLS))
    by_tag = {}
    for rid in TRAIL_RUNS:
        d = json.load(open(os.path.join(ROOT, "docs", "backtest_data", f"swing_bandcap_run_{rid}.json")))
        rows = {}
        for r in d.get("rows", []):
            rows.setdefault(r["tag"], []).append(r)
        for t, rs in rows.items():
            by_tag[t] = (rid, rs)  # a later run replaces an earlier one for the same tag
    out = {}
    for t in sorted(by_tag):
        rid, rs = by_tag[t]
        parts = t.split("__")
        long_tag = t == "gap_and_go" or (len(parts) >= 5 and parts[2] == "long" and parts[3] in ("1d", "1w"))
        if not long_tag or t in hourly or t not in main._STRATEGY_TAG_TO_REGISTRY_NAME:
            continue
        cands = []
        for r in rs:
            mode = sb.normalize_mode(r.get("band_cap"))
            if mode == "off":
                continue
            reg = sb.band_tag(t, mode)
            assert reg == r["band_tag"], (t, mode, reg, r["band_tag"])
            m = r.get("live") or {}
            pf, net, held = m.get("pfnet"), m.get("avg_net_pct"), m.get("avg_held_bars")
            if pf is None or net is None or not held or float(pf) <= sr.PFNET_LIVE_FLOOR:
                continue
            ent = main._registry_entry(reg)
            if ent is None or ent.metrics is None or not ent.metrics.pfnet > sr.PFNET_LIVE_FLOOR:
                continue
            rpd = float(net) / float(held)
            cands.append((mode, reg, round(rpd, 6), round(float(pf), 4), int(m["n"]), round(float(net), 4),
                          round(float(held), 2), rid))
        cands.sort(key=lambda c: (-c[2], c[6], c[0]))
        if cands:
            out[t] = tuple(cands)
    return out


def render(rows) -> str:
    lines = ['"""GENERATED by scripts/gen_swing_exit_variants.py (B-1500) - do not edit by hand; re-run the generator.',
             "",
             "live LONG swing tag -> exit variants with pooled PFnet > 1.00, in return-per-day order (first = best).",
             "Each variant: (mode, registry_tag, ret_per_day_pct, pfnet, n, avg_net_pct, avg_held_bars, run_id).",
             'mode: "live" = fixed resting stop; "live_lt<N>" peak-HIGH trail, "live_tr<N>" peak-CLOSE chandelier,',
             '"live_be<N>" net breakeven once the close peak gains N x R (scripts/swing_bandcap.py TRAIL_RULES)."""',
             "",
             "SWING_EXIT_VARIANTS = {"]
    for t, cands in rows.items():
        lines.append(f"    {t!r}: (")
        for c in cands:
            lines.append(f"        {c!r},")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main_cli(argv):
    text = render(build_rows())
    if "--check" in argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("swing_exit_variants_b1500.py is stale: run python3 scripts/gen_swing_exit_variants.py")
            return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main_cli(sys.argv[1:]))
