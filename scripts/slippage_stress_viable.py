"""B-422: analytic slippage/cost stress of every viable registry strategy.

Offline, registry-only (no replay, no network). Writes docs/SLIPPAGE_STRESS_VIABLE.md.
Run: python3 scripts/slippage_stress_viable.py

Model. Registry PFgross (g), PFnet (n) and win rate (w) come from a run at the
flat BASE_COST (0.8% round trip). Let L = gross loss total (PF denominator) and
K = (total cost) / L. Costs are charged per trade, so a fraction w of the cost
reduces gross wins and (1-w) adds to gross losses:
    n = (g - w*K) / (1 + (1-w)*K)   =>   K = (g - n) / (w + (1-w)*n)
Stressed cost c' scales K linearly (K' = K * c'/BASE_COST):
    n' = (g - w*K') / (1 + (1-w)*K')
Limits (honest): (1) assumes cost is a flat % of notional per trade, so extra
slippage is the same for every trade; real slippage is larger on illiquid names,
on stop-outs and in fast markets, so this is optimistic for thin symbols.
(2) w is the NET win rate, used as proxy for the share of cost landing on
winners (some gross winners become net losers, so this is approximate).
(3) Trades that flip sign are not re-classified. (4) Method A needs pfgross (> 0;
0.0 is the registry's "not recorded" placeholder) and win rate. Entries without it
use Method B (below), an ASSUMPTION-based approximation, labelled as such.
(5) Does not model fill failure or position-size impact. This is a screen, not
a replay: the empirical stressed replay is still owed (B-422).
"""
import collections
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import strategy_registry as sr  # noqa: E402

BASE_COST = 0.8
STRESS = (1.2, 1.6)
GROUPS = ["n200_swing_watchlist", "mcx_proxy", "full_nse", "etf", "index", "other"]


def group_of(universe):
    u = (universe or "").lower()
    if u.startswith("n200"):
        return "n200_swing_watchlist"
    if u.startswith("mcx"):
        return "mcx_proxy"
    if u.startswith("etf"):
        return "etf"
    if "index" in u:
        return "index"
    if u.startswith("full"):
        return "full_nse"
    return "other"


def stressed_pfnet(pfgross, pfnet, win_pct, cost):
    w = win_pct / 100.0
    k = (pfgross - pfnet) / (w + (1 - w) * pfnet)
    k2 = k * cost / BASE_COST
    return (pfgross - w * k2) / (1 + (1 - w) * k2)


AVG_LOSS_PCT = 3.0   # Method B assumed average losing-trade size, % of notional
AVG_LOSS_SENS = (2.0, 4.0)


def stressed_pfnet_b(pfnet, win_pct, cost, avg_loss_pct):
    """Method B (no PFgross): in units of the average net loss, avg win R =
    n*(1-w)/w. Extra cost d = (c'-0.8)/avg_loss_pct (both in %) shrinks every win by d
    and grows every loss by d: n' = n*(R-d)/(R*(1+d)). The average loss size is NOT in
    the registry, so it is an assumption (AVG_LOSS_PCT, sensitivity 2% and 4%)."""
    w = win_pct / 100.0
    if w <= 0:
        return None
    R = pfnet * (1 - w) / w
    d = (cost - BASE_COST) / avg_loss_pct
    return pfnet * (R - d) / (R * (1 + d))


def compute():
    rows = []
    for s in sr.REGISTRY:
        m = s.metrics
        if m is None or m.pfnet < sr.PFNET_LIVE_FLOOR:
            continue
        r = dict(name=s.name, group=group_of(m.universe), universe=m.universe,
                 cats=",".join(c.value for c in s.categories), tf=s.timeframe,
                 n=m.n_trades, pfnet=m.pfnet, pfgross=m.pfgross, win=m.win_rate_pct)
        r["method"] = None
        if m.win_rate_pct is not None and m.pfgross and m.pfgross >= m.pfnet:
            r["method"] = "A"
            for c in STRESS:
                r[c] = stressed_pfnet(m.pfgross, m.pfnet, m.win_rate_pct, c)
        elif m.win_rate_pct:
            r["method"] = "B"
            for c in STRESS:
                r[c] = stressed_pfnet_b(m.pfnet, m.win_rate_pct, c, AVG_LOSS_PCT)
                for a in AVG_LOSS_SENS:
                    r[(c, a)] = stressed_pfnet_b(m.pfnet, m.win_rate_pct, c, a)
        r["ok"] = r["method"] is not None
        rows.append(r)
    return rows


def render(rows):
    floor = sr.PFNET_LIVE_FLOOR
    L = ["# Slippage stress of viable strategies (B-422, analytic)", "",
         "Generated by `scripts/slippage_stress_viable.py` from `strategy_registry.REGISTRY` "
         f"(viable = PFnet >= {floor}). Registry metrics are not modified.", "",
         "## Formula and limits", "",
         f"Base run cost {BASE_COST}% round trip. With g = PFgross, n = PFnet, w = net win rate:",
         "", "    K  = (g - n) / (w + (1-w)*n)", "    K' = K * c'/0.8",
         "    n' = (g - w*K') / (1 + (1-w)*K')", "",
         "- Assumes extra slippage is a flat % of notional on every trade. Real slippage is worse on thin "
         "symbols, stop-outs and fast markets, so survivors here can still fail live; failures here fail for sure.",
         "- w (net win rate) approximates the share of cost falling on winners.",
         "- Needs PFgross and win %; entries missing either are listed as not computable (never guessed).",
         "- A screen, not a replay. Empirical stressed replay and a turnover filter are still owed.", ""]
    L += ["Method A = exact algebra from recorded PFgross. Method B = approximation from PFnet and win %, "
          f"assuming the average losing trade is {AVG_LOSS_PCT}% of notional (not recorded in the registry; "
          "sensitivity table below). Both are screens, not replays.", ""]
    L += ["## Survival by universe group", "",
          f"| Group | Viable | Computable | Survive 1.2% (>= {floor}) | Survive 1.6% | Not computable |",
          "|---|---|---|---|---|---|"]
    tot = collections.Counter()
    for g in GROUPS:
        rs = [r for r in rows if r["group"] == g]
        if not rs:
            continue
        ok = [r for r in rs if r["ok"]]
        a = sum(1 for r in ok if r[1.2] >= floor)
        b = sum(1 for r in ok if r[1.6] >= floor)
        L.append(f"| {g} | {len(rs)} | {len(ok)} | {a} | {b} | {len(rs)-len(ok)} |")
        tot.update(v=len(rs), c=len(ok), a=a, b=b)
    L.append(f"| **total** | {tot['v']} | {tot['c']} | {tot['a']} | {tot['b']} | {tot['v']-tot['c']} |")
    L += ["", "## Method B sensitivity to the assumed average loss size", "",
          f"| Avg loss % | Method B count | Survive 1.2% | Survive 1.6% |", "|---|---|---|---|"]
    bs = [r for r in rows if r["method"] == "B"]
    for a in (AVG_LOSS_SENS[0], AVG_LOSS_PCT, AVG_LOSS_SENS[1]):
        k = (lambda c: r[c]) if a == AVG_LOSS_PCT else None
        g = lambda r, c: r[c] if a == AVG_LOSS_PCT else r[(c, a)]
        L.append(f"| {a} | {len(bs)} | {sum(1 for r in bs if g(r,1.2) >= floor)} | "
                 f"{sum(1 for r in bs if g(r,1.6) >= floor)} |")
    L += ["", "## Survival by category (a strategy may sit in several)", "",
          "| Category | Computable | Survive 1.2% | Survive 1.6% |", "|---|---|---|---|"]
    cc = collections.defaultdict(lambda: [0, 0, 0])
    for r in rows:
        if not r["ok"]:
            continue
        for c in r["cats"].split(","):
            cc[c][0] += 1
            cc[c][1] += r[1.2] >= floor
            cc[c][2] += r[1.6] >= floor
    for c, v in sorted(cc.items()):
        L.append(f"| {c} | {v[0]} | {v[1]} | {v[2]} |")
    for g in GROUPS:
        rs = sorted([r for r in rows if r["group"] == g], key=lambda r: -(r.get(1.6) or 0))
        if not rs:
            continue
        L += ["", f"## {g}", "",
              "| Tag | Cat | TF | n | Method | PFnet 0.8% | PFnet 1.2% | PFnet 1.6% | 1.2 ok | 1.6 ok |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for r in rs:
            if r["ok"]:
                L.append(f"| {r['name']} | {r['cats']} | {r['tf']} | {r['n']} | {r['method']} | {r['pfnet']:.3f} | "
                         f"{r[1.2]:.3f} | {r[1.6]:.3f} | {'Y' if r[1.2] >= floor else 'N'} | "
                         f"{'Y' if r[1.6] >= floor else 'N'} |")
            else:
                L.append(f"| {r['name']} | {r['cats']} | {r['tf']} | {r['n']} | - | {r['pfnet']:.3f} | n/c | n/c | n/c | n/c |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    rows = compute()
    out = os.path.join(ROOT, "docs", "SLIPPAGE_STRESS_VIABLE.md")
    with open(out, "w") as f:
        f.write(render(rows))
    print("wrote", out, len(rows))
