#!/usr/bin/env python3
"""Classify every docs/ACTIONABLES_BACKLOG.md row into exactly one bucket.

Buckets: CLOSED, RUN_PENDING, BLOCKED_OWNER_OR_DATA, VERIFY_KOTAK, OPEN_TODO.
Usage: python3 scripts/backlog_status.py [--check] [--backlog P] [--out P]
--check exits 1 if docs/backlog_status_report.md is stale.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKLOG = os.path.join(ROOT, "docs", "ACTIONABLES_BACKLOG.md")
REPORT = os.path.join(ROOT, "docs", "backlog_status_report.md")
BUCKETS = ["CLOSED", "RUN_PENDING", "BLOCKED_OWNER_OR_DATA", "VERIFY_KOTAK", "OPEN_TODO"]

_PRIO = re.compile(r"^P[0-9]\b", re.I)
_STATUS_START = re.compile(
    r"^(DONE|CLOSED|DECIDED|MERGED|PENDING|PARTIAL|PARKED|OPEN|BLOCKED|HARNESS)", re.I)

# Ordered, first match wins. (bucket, regex on upper-cased status cell)
RULES = [
    ("BLOCKED_OWNER_OR_DATA", re.compile(r"^BLOCKED")),
    ("VERIFY_KOTAK", re.compile(r"PENDING[-_ ]VERIFY|VERIFY[-_ ]PENDING")),
    ("CLOSED", re.compile(r"^(DONE|CLOSED|DECIDED|MERGED)")),
    ("RUN_PENDING", re.compile(r"^HARNESS|^PARTIAL.*HARNESS[ _-]BUILT|RUN[_ -]PENDING|AWAITING[_ -]RUN")),
]


def split_row(line):
    return [c.strip() for c in line.strip().strip("|").split(" | ")]


def status_cell(cells):
    """Return the status text, handling shifted layouts.

    Standard: id | item | status | priority. Shifted: status or priority sits
    in the item column (id | P2 | DONE | ... or id | DONE | P1 | ...).
    """
    c1 = cells[1] if len(cells) > 1 else ""
    c2 = cells[2] if len(cells) > 2 else ""
    if _PRIO.match(c1):
        return c2
    if _STATUS_START.match(c1):
        return c1
    return c2


def classify(status):
    s = status.strip().upper()
    for bucket, rx in RULES:
        if rx.search(s):
            return bucket
    return "OPEN_TODO"


def parse(text):
    rows = []
    for line in text.splitlines():
        if re.match(r"^\| B-\d+", line):
            cells = split_row(line)
            rows.append((cells[0], classify(status_cell(cells))))
    return rows


def render(rows):
    out = ["# Backlog status report", "",
           "Generated by `scripts/backlog_status.py` from `docs/ACTIONABLES_BACKLOG.md`; do not hand-edit.", "",
           f"Total rows: {len(rows)}", "", "| Bucket | Count |", "|---|---|"]
    by = {b: [i for i, bb in rows if bb == b] for b in BUCKETS}
    for b in BUCKETS:
        out.append(f"| {b} | {len(by[b])} |")
    for b in BUCKETS:
        out += ["", f"## {b} ({len(by[b])})", "", ", ".join(by[b]) or "(none)"]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--backlog", default=BACKLOG)
    ap.add_argument("--out", default=REPORT)
    a = ap.parse_args(argv)
    with open(a.backlog, encoding="utf-8") as f:
        rows = parse(f.read())
    text = render(rows)
    if a.check:
        cur = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else ""
        if cur != text:
            print("backlog_status_report.md is stale; run scripts/backlog_status.py")
            return 1
        print("ok")
        return 0
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    for b in BUCKETS:
        print(b, sum(1 for _, bb in rows if bb == b))
    return 0


if __name__ == "__main__":
    sys.exit(main())
