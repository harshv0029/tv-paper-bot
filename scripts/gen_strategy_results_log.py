"""Regenerate docs/STRATEGY_RESULTS_LOG.md from strategy_registry.REGISTRY (the single
source of truth). One row per registered strategy tag: name, family/variant/dir/tf/params
parsed from the naming grammar (legacy tags shown as-is), PFnet, win %, n, held hrs,
universe, run ref. Usage: python3 scripts/gen_strategy_results_log.py [--check]"""
import pathlib
import sys

sys.path.insert(0, ".")
import strategy_edge_stats as es  # noqa: E402
import strategy_registry as sr  # noqa: E402

OUT = pathlib.Path("docs/STRATEGY_RESULTS_LOG.md")
OUT2 = pathlib.Path("docs/STRATEGY_PFNET_GT1.md")


def _cell(x):
    return str(x).replace("|", "/").replace("\n", " ")


def _expectancy(m):
    """Net expectancy per unit of average loss, derived at read time (B-539); blank if not derivable."""
    if m is None or m.pfnet is None or m.win_rate_pct is None:
        return ""
    e = es.expectancy_per_loss_unit(m.pfnet, m.win_rate_pct)
    return "" if e is None else f"{e:.3f}"


def _row(s):
    p = s.name.split("__")
    g = len(p) >= 6
    m = s.metrics
    v = s.is_viable()
    return "| " + " | ".join(_cell(x) for x in (
        s.name, p[0] if g else "(legacy)", p[1] if g else "", p[2] if g else "",
        p[3] if g else s.timeframe, p[4] if g else "",
        ",".join(getattr(c, "value", str(c)) for c in s.categories),
        f"{m.pfnet:.3f}" if m and m.pfnet is not None else "",
        f"{m.win_rate_pct:.1f}" if m and m.win_rate_pct is not None else "",
        _expectancy(m),
        m.n_trades if m else "", m.avg_held_hrs if m and m.avg_held_hrs is not None else "", m.avg_held_bars if m and getattr(m, "avg_held_bars", None) is not None else "",
        "n/a" if v is None else ("yes" if v else "no"),
        m.universe if m else "", m.run_ref if m else "")) + " |"


_COLS = ("| Strategy tag | Family | Variant | Dir | TF | Params | Categories | PFnet | Win % | "
         "Expectancy (per avg loss) | Trades | Avg held hrs | Avg held bars (raw) | Viable | Universe | Run ref |\n|" + "---|" * 16 + "\n")


def render_gt1():
    """Complete document set of every tag with PFnet > 1.0; currently viable = PFnet >= floor."""
    ok = [s for s in sr.REGISTRY if s.metrics and s.metrics.pfnet is not None and s.metrics.pfnet > 1.0]
    ok.sort(key=lambda d: (-d.metrics.pfnet, d.name))
    via = [s for s in ok if s.metrics.pfnet >= sr.PFNET_LIVE_FLOOR]
    mid = [s for s in ok if s.metrics.pfnet < sr.PFNET_LIVE_FLOOR]
    return ("# Strategies with PFnet > 1.0 (complete set)\n\n"
            "AUTO-GENERATED by `scripts/gen_strategy_results_log.py` from `strategy_registry.REGISTRY`; "
            "do not hand-edit. Viability is derived at read time: **currently viable = PFnet >= "
            f"{sr.PFNET_LIVE_FLOOR}**. Tags in 1.0-{sr.PFNET_LIVE_FLOOR} stay documented but are gated closed. "
            "Being viable does not create a live entry path; only wired tags trade. Sorted by PFnet.\n\n"
            f"## Currently viable (PFnet >= {sr.PFNET_LIVE_FLOOR}): {len(via)}\n\n" + _COLS
            + "\n".join(_row(s) for s in via)
            + f"\n\n## PFnet > 1.0 but below {sr.PFNET_LIVE_FLOOR} (documented, not viable): {len(mid)}\n\n" + _COLS
            + "\n".join(_row(s) for s in mid) + "\n")


def render():
    head = ("# Strategy results log (PFnet, win %, variant details)\n\n"
            "AUTO-GENERATED from `strategy_registry.REGISTRY` by "
            "`scripts/gen_strategy_results_log.py` - do not hand-edit; edit the registry "
            "and regenerate (a test fails if this file is stale). Every tag is its own row, "
            "never pooled. Naming grammar: `<family>__<variant>__<dir>__<tf>__<params>__v<N>`. "
            f"Viability floor PFnet >= {sr.PFNET_LIVE_FLOOR}. Blank metrics = not measured yet "
            "(never guessed). Expectancy = p*R-(1-p) in units of the average loss, derived at read "
            "time from PFnet and win % via `strategy_edge_stats.py` (B-539); >0 iff PFnet>1.\n\n"
            + _COLS)
    rows = [_row(s) for s in sorted(sr.REGISTRY, key=lambda d: d.name)]
    return head + "\n".join(rows) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text and OUT2.exists() and OUT2.read_text() == render_gt1() else 1)
    OUT.write_text(text)
    OUT2.write_text(render_gt1())
    print(f"wrote {OUT} ({len(sr.REGISTRY)} strategies)")
